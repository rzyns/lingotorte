// lt-5lb.5: `node scripts/workflows/extract-structure.cli.ts [--check]` writes (or checks) the committed
// pass-1 structure file docs/workflows/as-is/structure.yaml. Deterministic for an unchanged tree.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { stringify } from 'yaml';
import { extractStructure } from './extract-structure.ts';

const root = fileURLToPath(new URL('../../', import.meta.url));
export const STRUCTURE_PATH = 'docs/workflows/as-is/structure.yaml';
const HEADER = '# GENERATED by scripts/workflows/extract-structure.cli.ts from apps/web/src and apps/local-service/src.\n# Do not edit: run `node scripts/workflows/extract-structure.cli.ts`. Every entry carries path:line provenance.\n';

export function renderStructureYaml(rootDir: string): string {
  return HEADER + stringify(extractStructure(rootDir), { lineWidth: 0, aliasDuplicateObjects: false });
}

const check = process.argv.includes('--check');
const next = renderStructureYaml(root);
if (check) {
  let current = '';
  try { current = readFileSync(new URL(STRUCTURE_PATH, `file:///${root.replace(/\\/g, '/')}`), 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== next) {
    console.error(`${STRUCTURE_PATH} is stale: run node scripts/workflows/extract-structure.cli.ts`);
    process.exit(1);
  }
  console.log(`${STRUCTURE_PATH} is current`);
} else {
  writeFileSync(new URL(STRUCTURE_PATH, `file:///${root.replace(/\\/g, '/')}`), next);
  console.log(`wrote ${STRUCTURE_PATH}`);
}
