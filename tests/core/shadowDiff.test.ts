async function withFile<T>(run: (file: string) => Promise<T> | T): Promise<T> {
  const root = await mkdtemp(join(tmpdir(), 'lt-584-3-'));
  try { return await run(join(root, 'state.db')); } finally { await rm(root, { recursive: true, force: true }); }
}

describe('lt-584.3 shadow comparison: tables vs blob', () => {
  it('an empty database is shadow-equal', () => {
    const db = SqliteLocalPersistence.open(':memory:');
    try { expectShadowEqual(db); expect(Object.keys(db.loadSnapshotShadowDiff().collections).sort()).toEqual(Object.keys(createEmptyLocalStoreSnapshot()).sort()); } finally { db.close(); }
  });

  it('every collection with every optional field and legal orphan rows reproduces exactly, across reopen', async () => {
    await withFile(file => {
      let db = SqliteLocalPersistence.open(file);
      try {
        const written = fullSnapshot();
        db.saveSnapshot(written, AT);
        const diff = db.loadSnapshotShadowDiff(written);
        expect(diff.equal).toBe(true);
        for (const [name, c] of Object.entries(diff.collections)) expect(c.blob, name).toBeGreaterThan(0);
        expect(diff.collections.cues).toMatchObject({ blob: 2, tables: 2 });
        expect(diff.collections.transcriptWordTimings).toMatchObject({ blob: 2, tables: 2 });
        expect(diff.collections.mediaObservations).toMatchObject({ blob: 2, tables: 2 });
        db.close(); db = SqliteLocalPersistence.open(file);
        expectShadowEqual(db, written);
      } finally { db.close(); }
    });
  });

  it.each([
    ['changed', 'savedItems', "UPDATE saved_item SET notes = 'tampered'", { missing: 0, extra: 0, changed: 1 }],
    ['changed (optional dropped)', 'transcriptWordTimings', 'UPDATE transcript_word_timing SET speaker_id = NULL WHERE speaker_id IS NOT NULL', { missing: 0, extra: 0, changed: 1 }],
    ['missing', 'mediaObservations', "DELETE FROM media_file_observation WHERE id = 'obs-orphan'", { missing: 1, extra: 0, changed: 0 }],
    ['extra', 'exportJobs', "INSERT INTO export_job SELECT 'exp-2', kind, status, started_at, completed_at, destination_kind, destination_label, manifest_sha256, content_summary_json, error_code FROM export_job", { missing: 0, extra: 1, changed: 0 }],
  ] as const)('reports a %s %s row and only that collection', async (_, collection, sql, counts) => {
    await withFile(file => {
      const db = SqliteLocalPersistence.open(file);
      try {
        const written = fullSnapshot();
        db.saveSnapshot(written, AT);
        const raw = new DatabaseSync(file); raw.exec(sql); raw.close();
        const diff = db.loadSnapshotShadowDiff(written);
        expect(diff.equal).toBe(false);
        expect(Object.entries(diff.collections).filter(([, c]) => !c.equal).map(([name]) => name)).toEqual([collection]);
        expect(diff.collections[collection]).toMatchObject({ ...counts, equal: false });
      } finally { db.close(); }
    });
  });

  it('the diff is read-only: no revision bump, no table change', async () => {
    await withFile(file => {
      const db = SqliteLocalPersistence.open(file);
      try {
        db.saveSnapshot(fullSnapshot(), AT);
        const before = db.loadVersionedSnapshot();
        db.loadSnapshotShadowDiff(); db.loadSnapshotShadowDiff();
        expect(db.loadVersionedSnapshot()).toEqual(before);
      } finally { db.close(); }
    });
  });

  it('withShadow checks after every successful save/restore and never after a failed one', () => {
    const inner = SqliteLocalPersistence.open(':memory:');
    const spy = vi.spyOn(inner, 'loadSnapshotShadowDiff');
    const db = withShadow(inner);
    try {
      const first = db.saveSnapshot(fullSnapshot(), AT);
      expect(spy).toHaveBeenCalledTimes(1);
      expect(() => db.saveSnapshot(fullSnapshot(), AT, 'rev:999')).toThrow(/Durable state changed/);
      expect(spy).toHaveBeenCalledTimes(1);
      db.saveSnapshot(new LocalStore(db.loadSnapshot()).snapshot());
      expect(spy).toHaveBeenCalledTimes(2);
      expect(db.loadVersionedSnapshot().revision).not.toBe(first);
    } finally { inner.close(); }
  });
});
